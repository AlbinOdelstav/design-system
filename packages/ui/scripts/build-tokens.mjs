/**
 * Token CSS generator.
 *
 * Reads the single source of truth (src/tokens/tokens.data.mjs) and emits a
 * `:root { --token: value }` stylesheet. Runs under plain `node` (no TS loader)
 * because it imports the `.mjs` data module directly.
 *
 * Outputs:
 *   - src/tailwind/styles.css  (so source consumers / showcase HMR resolve the
 *                               `@import './styles.css'` in base.css)
 *   - dist/styles.css          (published artifact)
 *   - dist/base.css            (published copy of src/tailwind/base.css)
 *
 * Re-run via `npm run build:tokens` after editing tokens.
 */
import { mkdir, writeFile, copyFile, access } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  colors,
  radius,
  shadow,
  fontFamily,
  fontSize,
  fontWeight,
  letterSpacing,
  duration,
  easing,
  borderWidth,
  cssVarName,
} from '../src/tokens/tokens.data.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const uiRoot = resolve(__dirname, '..');
const srcTailwind = resolve(uiRoot, 'src', 'tailwind');
const distDir = resolve(uiRoot, 'dist');

function line(name, value) {
  return `  ${name}: ${value};`;
}

function buildRoot() {
  const lines = [];

  lines.push('  /* colors */');
  for (const [key, value] of Object.entries(colors)) {
    lines.push(line(cssVarName('color', key), value));
  }

  lines.push('  /* radii */');
  for (const [key, value] of Object.entries(radius)) {
    lines.push(line(cssVarName('radius', key), value));
  }

  lines.push('  /* shadows */');
  for (const [key, value] of Object.entries(shadow)) {
    lines.push(line(cssVarName('shadow', key), value));
  }

  lines.push('  /* typography */');
  for (const [key, value] of Object.entries(fontFamily)) {
    lines.push(line(cssVarName('fontFamily', key), value));
  }
  for (const [key, [size, lineHeight]] of Object.entries(fontSize)) {
    lines.push(line(cssVarName('fontSize', key), size));
    lines.push(line(cssVarName('lineHeight', key), lineHeight));
  }
  for (const [key, value] of Object.entries(fontWeight)) {
    lines.push(line(cssVarName('fontWeight', key), value));
  }
  for (const [key, value] of Object.entries(letterSpacing)) {
    lines.push(line(cssVarName('letterSpacing', key), value));
  }

  lines.push('  /* motion */');
  for (const [key, value] of Object.entries(duration)) {
    lines.push(line(cssVarName('duration', key), value));
  }
  for (const [key, value] of Object.entries(easing)) {
    lines.push(line(cssVarName('easing', key), value));
  }

  lines.push('  /* border widths */');
  for (const [key, value] of Object.entries(borderWidth)) {
    lines.push(line(cssVarName('borderWidth', key), value));
  }

  return `/* AUTO-GENERATED by scripts/build-tokens.mjs — do not edit by hand. */\n:root {\n${lines.join(
    '\n',
  )}\n}\n`;
}

async function exists(path) {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

async function main() {
  const css = buildRoot();

  // 1. Source copy: required for source-level consumption (showcase HMR, tests).
  await mkdir(srcTailwind, { recursive: true });
  await writeFile(resolve(srcTailwind, 'styles.css'), css, 'utf8');

  // 2. Dist copies: only when a dist build exists (tsup runs before this in the
  //    build script). Create the dir so a standalone `build:tokens` still works.
  await mkdir(distDir, { recursive: true });
  await writeFile(resolve(distDir, 'styles.css'), css, 'utf8');

  const baseSrc = resolve(srcTailwind, 'base.css');
  if (await exists(baseSrc)) {
    await copyFile(baseSrc, resolve(distDir, 'base.css'));
  }

  console.log('build-tokens: wrote styles.css (src + dist) and dist/base.css');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
